const DICTS: Record<Lang, Record<TKey, string>> = { tr, en };

export type Translate = (key: TKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): Translate {
  return (key, vars) => {
    let text = DICTS[lang][key];
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  };
}

/** Error strings from the content script are TKeys; anything else is shown as-is. */
export function translateError(t: Translate, error: string): string {
  return error in tr ? t(error as TKey) : error;
}

export function browserLang(): Lang {
  return chrome.i18n.getUILanguage().toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

